from django.shortcuts import render, redirect
from .models import Lead, Newsletter
from .forms import EnquiryForm, NewsletterForm
from django.contrib import messages
from company.models import Company
from django.core.mail import EmailMessage
from datetime import datetime
from decouple import config


def contact_us(request):
    title = "Contact Us"
    company = Company.objects.select_related().first()  # Optimized query

    if request.method == "POST":
        form = EnquiryForm(request.POST)
        if form.is_valid():
            # Save the inquiry to database
            Lead.objects.create(**form.cleaned_data)

            try:
                current_time = datetime.now().strftime("%A, %B %d, %Y at %I:%M %p")
                mail_subject = f"📩 New Inquiry from {form.cleaned_data['full_name']} – Tareon Service Limited"

                message = f"""
                <div style="font-family: Arial, sans-serif; color: #333;">
                    <h2 style="color: #003366; margin-bottom: 10px;">New Business Inquiry Notification 🚨</h2>
                    <p style="font-size: 15px; color: #444;">
                        You’ve received a new inquiry via the official Tareon Service Limited website.
                        Kindly review the details below and take the appropriate follow-up action.
                    </p>

                    <hr>
                    <p><strong>Name:</strong> {form.cleaned_data["full_name"]}</p>
                    <p><strong>Email:</strong> {form.cleaned_data["email"]}</p>
                    <p><strong>Phone:</strong> {form.cleaned_data["phone_number"]}</p>
                    <p><strong>Company:</strong> {form.cleaned_data["company_name"]}</p>
                    <p><strong>Job Title:</strong> {form.cleaned_data["job_title"]}</p>
                    <p><strong>Service Interested In:</strong> {form.cleaned_data["service"]}</p>
                    <p><strong>Channel:</strong> {form.cleaned_data["channel"]}</p>
                    <p><strong>Message:</strong><br>{form.cleaned_data["message"]}</p>
                    <hr>
                    <p style="font-size: 14px; color: #555;">Received on <strong>{current_time}</strong></p>
                    <br>
                    <p style="font-size: 13px; color: #777;">
                        — This message was automatically generated by the Tareon Service Limited Web Platform.<br>
                        <em>Securing tomorrow, today.</em> 🔒
                    </p>
                </div>
                """

                # 👇 New part starts here
                user_name = form.cleaned_data["full_name"]
                user_email = form.cleaned_data["email"]

                send_email = EmailMessage(
                    mail_subject,
                    message,
                    from_email=f"{user_name} <{user_email}>",   # 👈 Shows user's name & email
                    to=[config("EMAIL_HOST_USER")],             # 👈 Sends to your company Gmail
                    reply_to=[user_email],                      # 👈 Clicking “Reply” goes to the user
                )
                send_email.content_subtype = "html"
                send_email.send()
                # 👆 New part ends here

            except Exception as e:
                print("Email sending failed:", e)

            messages.success(
                request,
                "✅ Thank you for contacting Tareon Service Limited. We’ve received your inquiry and our support team will respond promptly."
            )
            return redirect("contact_us")

        else:
            messages.error(
                request,
                "⚠️ Please correct the highlighted fields below and try again."
            )

    else:
        form = EnquiryForm()

    context = {
        "company": company,
        "form": form,
        "title": title,
    }
    return render(request, "enquiry/contact_us.html", context)



def subscribe(request):
    if request.method == "POST":
        form = NewsletterForm(request.POST)
        if form.is_valid():
            data = Newsletter()
            data.email = form.cleaned_data['email']
            data.full_name = form.cleaned_data['full_name']  # Fixed field assignment
            data.save()

            # Send email notification
            try:
                current_time = datetime.now()
                mail_subject = 'Newsletter Subscription Alert'
                message = f'{form.cleaned_data["email"]} subscribed to the newsletter on {current_time}'
                to_email = config('EMAIL_HOST_USER')
                send_email = EmailMessage(mail_subject, message, to=[to_email])
                send_email.send()
            except:
                pass

            messages.success(request, "You're officially part of Tareon's newsletter community!")
            return redirect(request.META.get('HTTP_REFERER', 'contact_us'))

    return redirect(request.META.get('HTTP_REFERER', 'contact_us'))
